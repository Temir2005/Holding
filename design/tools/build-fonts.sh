#!/bin/sh
# Builds the site's self-hosted fonts for the «Чертёж» design: instanced and subset woff2 files,
# one per unicode subset, plus fonts.css with unicode-range and the OFL licences.
#   design/tools/build-fonts.sh <out-dir>
# Sources: fontsource packages downloaded by design/tools/fonts.sh (design/concepts/_shared/fonts).
# Runs fonttools in a throwaway python:3.12-slim container; nothing is installed on the host.
set -e
OUT="${1:?usage: build-fonts.sh <out-dir>}"
mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd)"
cd "$(dirname "$0")/.."
SRC="$PWD/concepts/_shared/fonts"
docker run --rm -v "$SRC:/src:ro" -v "$OUT:/out" python:3.12-slim sh -c '
set -e
pip -q install fonttools brotli >/dev/null 2>&1
LATIN="U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD"
CYR="U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116"
CYREXT="U+0460-052F,U+1C80-1C8A,U+20B4,U+2DE0-2DFF,U+A640-A69F,U+FE2E-FE2F"
range() { case $1 in latin) echo $LATIN;; cyrillic) echo $CYR;; cyrillic-ext) echo $CYREXT;; esac; }
css=/out/fonts.css
echo "/* Generated by design/tools/build-fonts.sh — do not edit. Licences: OFL-*.txt next to this file. */" > $css
for s in latin cyrillic cyrillic-ext; do
  # Geologica: sharpness pinned to 60, no cursive/slant; weight axis 200–700 kept.
  python -m fontTools.varLib.instancer /src/fontsource-variable_geologica/files/geologica-$s-full-normal.woff2 \
    SHRP=60 CRSV=0 slnt=0 wght=200:700 -o /tmp/g.ttf -q
  python -c "from fontTools.ttLib import TTFont;f=TTFont(\"/tmp/g.ttf\");f.flavor=\"woff2\";f.save(\"/out/geologica-$s.woff2\")"
  echo "@font-face{font-family:\"Geologica\";font-style:normal;font-display:swap;font-weight:200 700;src:url(./geologica-$s.woff2) format(\"woff2\");unicode-range:$(range $s)}" >> $css
  for w in 400 500; do
    cp /src/fontsource_ibm-plex-mono/files/ibm-plex-mono-$s-$w-normal.woff2 /out/ibm-plex-mono-$s-$w.woff2
    echo "@font-face{font-family:\"IBM Plex Mono\";font-style:normal;font-display:swap;font-weight:$w;src:url(./ibm-plex-mono-$s-$w.woff2) format(\"woff2\");unicode-range:$(range $s)}" >> $css
  done
done
cp /src/fontsource-variable_geologica/LICENSE /out/OFL-Geologica.txt
cp /src/fontsource_ibm-plex-mono/LICENSE /out/OFL-IBM-Plex-Mono.txt
ls -l /out | awk "NR>1 {printf \"%6.1f KB  %s\n\", \$5/1024, \$9}"
'
