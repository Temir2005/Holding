/** Crops of new UI on the dev site: project neighbours, menu button, form pending. */
const path = require('path')
const { chromium } = require('@playwright/test')
const BASE = 'http://localhost:5173'
;(async () => {
  const [out] = process.argv.slice(2)
  const browser = await chromium.launch()
  for (const w of [375, 1440]) {
    const page = await browser.newPage({ viewport: { width: w, height: w < 500 ? 812 : 900 } })
    await page.goto(BASE + '/ru/projects/zhk-proekt-a', { waitUntil: 'networkidle' })
    const nav = page.locator('nav[aria-label="Соседние объекты"]')
    await nav.scrollIntoViewIfNeeded()
    await page.waitForTimeout(1500)
    const end = nav.locator('xpath=ancestor::section[1]')
    if (w > 500) await nav.locator('a').last().hover()
    await page.waitForTimeout(700)
    await end.screenshot({ path: path.join(out, `neighbors-${w}.png`) })
    await page.close()
  }
  // form pending: hold the lead request
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await page.route('**/api/v1/leads', async (r) => { await new Promise((res) => setTimeout(res, 4000)); await r.fulfill({ status: 201, contentType: 'application/json', body: JSON.stringify({ id: '00000000-0000-0000-0000-000000000000' }) }) })
  await page.goto(BASE + '/ru/clients#contacts', { waitUntil: 'networkidle' })
  const form = page.locator('form').first()
  await form.scrollIntoViewIfNeeded()
  await page.waitForTimeout(1200)
  await form.locator('input[name=name]').fill('Тест')
  await form.locator('input[name=phone]').fill('+7 700 000 00 00')
  const before = await form.evaluate((f) => f.offsetHeight)
  await form.locator('button[type=submit]').click()
  await page.waitForTimeout(500)
  await form.screenshot({ path: path.join(out, 'form-pending-1440.png') })
  await page.waitForTimeout(4500)
  const ok = page.locator('[role=status]').first()
  const after = await ok.evaluate((f) => f.offsetHeight)
  await ok.screenshot({ path: path.join(out, 'form-success-1440.png') })
  console.log(`form height before=${before} success=${after}`)
  await browser.close()
})()
