#!/bin/sh
# Generates fonts.css: @font-face for the finalist fonts, split by subset like fontsource does.
LATIN="U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD"
CYR="U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116"
CYREXT="U+0460-052F,U+1C80-1C8A,U+20B4,U+2DE0-2DFF,U+A640-A69F,U+FE2E-FE2F"
face() { # family dir prefix axisOrWeight weightRange [stretch]
  for s in latin cyrillic cyrillic-ext; do
    case $s in latin) R=$LATIN;; cyrillic) R=$CYR;; cyrillic-ext) R=$CYREXT;; esac
    printf "@font-face{font-family:'%s';font-style:normal;font-display:swap;font-weight:%s;%ssrc:url(fonts/%s/files/%s-%s-%s-normal.woff2) format('woff2-variations');unicode-range:%s}\n" \
      "$1" "$5" "${6:+font-stretch:$6;}" "$2" "$3" "$s" "$4" "$R"
  done
}
{
  echo "/* Generated by gen-fonts.sh — finalist fonts for the stage-0 prototypes (all verified for Kazakh via tools/cmap.cjs). */"
  face 'Geologica' fontsource-variable_geologica geologica full '100 900'
  face 'Onest' fontsource-variable_onest onest wght '100 900'
  face 'Science Gothic' fontsource-variable_science-gothic science-gothic standard '100 900' '50% 200%'
  face 'Tektur' fontsource-variable_tektur tektur standard '400 900' '75% 100%'
  face 'Roboto Flex' fontsource-variable_roboto-flex roboto-flex standard '100 1000' '25% 151%'
  face 'Inter' fontsource-variable_inter inter opsz '100 900'
  face 'Geist' fontsource-variable_geist geist wght '100 900'
  face 'Geist Mono' fontsource-variable_geist-mono geist-mono wght '100 900'
  face 'Golos Text' fontsource-variable_golos-text golos-text wght '400 900'
  for w in 400 500 600; do
    for s in latin cyrillic cyrillic-ext; do
      case $s in latin) R=$LATIN;; cyrillic) R=$CYR;; cyrillic-ext) R=$CYREXT;; esac
      printf "@font-face{font-family:'IBM Plex Mono';font-style:normal;font-display:swap;font-weight:%s;src:url(fonts/fontsource_ibm-plex-mono/files/ibm-plex-mono-%s-%s-normal.woff2) format('woff2');unicode-range:%s}\n" "$w" "$s" "$w" "$R"
    done
  done
  for w in 700 800 900; do
    for s in latin cyrillic cyrillic-ext; do
      case $s in latin) R=$LATIN;; cyrillic) R=$CYR;; cyrillic-ext) R=$CYREXT;; esac
      printf "@font-face{font-family:'Fira Sans Extra Condensed';font-style:normal;font-display:swap;font-weight:%s;src:url(fonts/fontsource_fira-sans-extra-condensed/files/fira-sans-extra-condensed-%s-%s-normal.woff2) format('woff2');unicode-range:%s}\n" "$w" "$s" "$w" "$R"
    done
  done
} > fonts.css
